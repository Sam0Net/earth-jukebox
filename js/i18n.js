const CLAVE_STORAGE = 'earth_jukebox_lang'
let idiomaActual = 'en'

try {
  const guardado = localStorage.getItem(CLAVE_STORAGE)
  if (guardado === 'es' || guardado === 'en') {
    idiomaActual = guardado
  } else {
    idiomaActual = 'en'
  }
} catch {
  idiomaActual = 'en'
}

const oyentesCambio = new Set()

export function obtenerIdioma() {
  return idiomaActual
}

export function t(clave, params = {}) {
  const dict = traducciones[idiomaActual] || traducciones.en
  let texto = dict[clave] || (traducciones.en && traducciones.en[clave]) || clave

  if (params && typeof params === 'object') {
    for (const [k, v] of Object.entries(params)) {
      texto = texto.replaceAll(`{${k}}`, v)
    }
  }
  return texto
}

export function suscribirCambioIdioma(callback) {
  oyentesCambio.add(callback)
  return () => oyentesCambio.delete(callback)
}

export function aplicarTraduccionesDOM() {
  if (typeof document === 'undefined') return

  if (document.documentElement) {
    document.documentElement.lang = idiomaActual
  }

  // Textos directos
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const clave = el.getAttribute('data-i18n')
    if (clave) {
      el.textContent = t(clave)
    }
  })

  // Atributos como aria-label, title, placeholder
  document.querySelectorAll('[data-i18n-attrs]').forEach((el) => {
    const pares = el.getAttribute('data-i18n-attrs').split(';')
    for (const par of pares) {
      const [attr, clave] = par.split(':').map((s) => s.trim())
      if (attr && clave) {
        el.setAttribute(attr, t(clave))
      }
    }
  })
}

export function establecerIdioma(nuevoIdioma) {
  if (nuevoIdioma !== 'en' && nuevoIdioma !== 'es') return
  idiomaActual = nuevoIdioma
  try {
    localStorage.setItem(CLAVE_STORAGE, nuevoIdioma)
  } catch {
    // ignorar error de storage en entornos restringidos
  }

  aplicarTraduccionesDOM()

  for (const fn of oyentesCambio) {
    try {
      fn(idiomaActual)
    } catch (e) {
      console.warn('Error en listener de idioma:', e)
    }
  }
}

export function alternarIdioma() {
  const siguiente = idiomaActual === 'en' ? 'es' : 'en'
  establecerIdioma(siguiente)
  return siguiente
}
